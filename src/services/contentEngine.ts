/** Detailed image prompt for food/recipes (for AI image services). */
export function buildImagePrompt(topic: string, lang: 'ru' | 'en' = 'ru'): string {
  const t = norm(topic);
  if (/оливь/.test(t)) {
    return 'Classic Russian salad Olivier in a crystal bowl with mayonnaise and green peas, on a festive New Year table with champagne glasses, candles, snowflakes and elegant restaurant tableware, food photography, warm lighting, top-down and 45-degree angle, appetizing, high detail';
  }
  if (/салат/.test(t)) {
    return `Beautiful appetizing salad «${topic}» in an elegant bowl on a festive restaurant table, fresh herbs, soft warm lighting, professional food photography, shallow depth of field`;
  }
  if (isRecipeTopic(topic)) {
    return `Delicious dish «${topic}» beautifully plated on a festive or restaurant table, garnish, soft lighting, professional food photography, appetizing close-up`;
  }
  // Fashion / style / trends
  if (/мод|fashion|тренд|стил|одежд|осен|lookbook|подиум|runway/.test(t)) {
    return `Editorial fashion photo for «${topic}»: stylish autumn 2026 runway looks, rich jewel tones and earth colors, wool cashmere coats, tailored silhouettes, leather boots, statement accessories, professional fashion photography, magazine cover quality, sharp detail, elegant models, city or studio background`;
  }
  return lang === 'ru'
    ? `High-quality professional photo illustrating: ${topic}. Realistic, detailed, magazine style, clear subject related to the topic, bright composition`
    : `High-quality professional photo illustrating: ${topic}. Realistic, detailed, magazine style, clear subject related to the topic, bright composition`;
}
