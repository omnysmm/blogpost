// Generic recipe builder for other dishes
function genericRecipe(topic: string): { ingredients: string[]; steps: string[] } {
  return {
    ingredients: [
      `Основной продукт блюда «${topic}» — 400–500 г`,
      'Овощи или гарнир по классике блюда — 200 г',
      'Лук / зелень — по вкусу',
      'Соль, перец, любимые специи',
      'Масло или соус для подачи — 1–2 ст. л.',
    ],
    steps: [
      `Подготовьте все продукты для блюда «${topic}» — мойте, чистите, нарежьте.`,
      'Обработайте основной продукт (отварите, обжарьте или запеките) до готовности.',
      'Добавьте ароматические компоненты и приправы, доведите вкус до баланса.',
      'Соберите блюдо, прогрейте при необходимости и подайте с зеленью.',
    ],
  };
}

function isRecipeTopic(topic: string): boolean {
  const t = norm(topic);
  return /рецепт|салат|блюдо|пирог|суп|торт|паста|плов|борщ|стейк|пюже|десерт|оливь|готовить|кулинар/.test(t);
}

function isOlivier(topic: string): boolean {
  return /оливь/.test(norm(topic));
}

