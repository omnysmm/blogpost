function parseMarkdown(text: string): string {
  return text
    .split('\n')
    .map(line => {
      if (line.startsWith('## ')) return `<h2 class="text-xl font-bold text-slate-900 mt-8 mb-3">${line.slice(3)}</h2>`;
      if (line.startsWith('### ')) return `<h3 class="text-lg font-semibold text-slate-800 mt-6 mb-2">${line.slice(4)}</h3>`;
      if (line.startsWith('**') && line.endsWith('**')) return `<p class="font-semibold text-slate-800 mt-4 mb-2">${line.slice(2, -2)}</p>`;
      if (line.startsWith('- ')) return `<li class="ml-5 text-slate-700 leading-relaxed list-disc">${line.slice(2)}</li>`;
      if (line.trim() === '') return '';
      return `<p class="text-slate-700 leading-relaxed mb-2">${line}</p>`;
    })
    .join('\n');
}

